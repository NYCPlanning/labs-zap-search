import { HttpException, HttpStatus, Injectable } from "@nestjs/common";
import jwt from "jsonwebtoken";
import moment from "moment";
import * as fetch from "node-fetch";
import { ConfigService } from "../config/config.service";
import { ContactService } from "../contact/contact.service";

/**
 * This class describes the central auth service. Two public methods are available.
 * This service is responsible for verifying and generating new tokens.
 *
 * @class      AuthService (name)
 */
@Injectable()
export class AuthService {
  // required env variables
  CRM_SIGNING_SECRET = "";
  NYCID_OIDC_ENDPOINT = "";
  NYCID_RELYING_PARTY_CLIENT_ID = "";

  constructor(
    private readonly config: ConfigService,
    private readonly contactService: ContactService
  ) {
    this.CRM_SIGNING_SECRET = this.config.get("CRM_SIGNING_SECRET");
    this.NYCID_OIDC_ENDPOINT = this.config.get("NYCID_OIDC_ENDPOINT");
    this.NYCID_RELYING_PARTY_CLIENT_ID = this.config.get(
      "NYCID_RELYING_PARTY_CLIENT_ID"
    );
  }

  /**
   * NYC.ID Authorization Code + PKCE login. Exchanges the authorization code
   * for an NYC.ID id_token, then issues our own ZAP token for the matching
   * CRM contact. Returns the ZAP token and the NYC.ID profile claims.
   *
   * @param      {string}  code          The authorization code from NYC.ID's redirect
   * @param      {string}  codeVerifier  The PKCE verifier the client generated
   * @param      {string}  redirectUri   The redirect_uri used in the authorize request
   */
  public async generateNewTokenFromCode(
    code: string,
    codeVerifier: string,
    redirectUri: string
  ) {
    const idTokenClaims = await this.exchangeNYCIDCode(
      code,
      codeVerifier,
      redirectUri
    );    
    const { contactid } = await this.lookupContact(idTokenClaims.email);

    return {
      ZAPToken: this.signNewToken(contactid),
      idTokenClaims
    };
  }

  /**
   * Calls NYC.ID's token endpoint and returns the decoded id_token claims.
   *
   * The id_token signature is not checked: per OpenID Connect Core 3.1.3.7,
   * TLS validation of the token endpoint may stand in for it when the token is
   * received directly from NYC.ID. We still check audience and expiry.
   */
  private async exchangeNYCIDCode(
    code: string,
    codeVerifier: string,
    redirectUri: string
  ): Promise<any> {
    if (!code || !codeVerifier || !redirectUri) {
      throw new HttpException(
        "Missing code, codeVerifier, or redirectUri",
        HttpStatus.UNAUTHORIZED
      );
    }

    const response = await fetch(`${this.NYCID_OIDC_ENDPOINT}/token`, {
      method: "POST",
      headers: { "Content-Type": "application/x-www-form-urlencoded" },
      body: new URLSearchParams({
        client_id: this.NYCID_RELYING_PARTY_CLIENT_ID,
        code,
        redirect_uri: redirectUri,
        grant_type: "authorization_code",
        code_verifier: codeVerifier,
        code_challenge_method: "S256",
      }).toString()
    });
    const body = await response.json();
    if (!response.ok || !body.id_token) {
      throw new HttpException(
        `NYC.ID token exchange failed: ${body.error_description ||
          body.error ||
          response.status}`,
        HttpStatus.UNAUTHORIZED
      );
    }

     const userinfoResponse = await fetch(`${this.NYCID_OIDC_ENDPOINT}/userinfo`, {
      headers: { Authorization: `Bearer ${body.access_token}` }
    });
    const userinfo = await userinfoResponse.json();

    const claims: any = jwt.decode(body.id_token);
    const access_claims: any = jwt.decode(body.access_token);

    if (
      !claims ||
      claims.aud !== this.NYCID_RELYING_PARTY_CLIENT_ID ||
      claims.exp < moment().unix()
    ) {
      throw new HttpException("Invalid NYC.ID id_token", HttpStatus.UNAUTHORIZED);
    }

    return userinfo;
  }

  /**
   * Validates the current signed JWT generated by ZAP API.
   *
   * @param      {string}  token   The token
   */
  public validateCurrentToken(token: string) {
    return this.verifyCRMToken(token);
  }

  /**
   * Lookup a contact entity by email or, if present, a contact ID.
   * Throws an unauthorized error if a contact is not found
   *
   * @param      {string}  mail    An email account to be found in CRM
   */
  private async lookupContact(mail: string) {
    try {
      return this.contactService.findByEmail(mail);
    } catch (e) {
      throw new HttpException(
        `
        CRM user not found. Please make sure your e-mail is associated with an assignment.
      `,
        HttpStatus.UNAUTHORIZED
      );
    }
  }

  /**
   * Verifies a JWT with the CRM signing secret. Returns a token object.
   *
   * @param      {string}  token   The token
   * @return     {any}     { mail: 'string', exp: 'string' }
   */
  private verifyCRMToken(token): any {
    const { CRM_SIGNING_SECRET } = this;

    return this.verifyToken(token, CRM_SIGNING_SECRET);
  }

  /**
   * Generates a new ZAP API token, including the contact id
   *
   * @param      {string}  contactid  The CRM contactid
   * @param      {string}  exp        A string coercable to a Date
   */
  private signNewToken(
    contactid: string,
    exp: number = moment()
      .add(1, "days")
      .unix()
  ): string {
    const { CRM_SIGNING_SECRET } = this;

    return jwt.sign({ contactid, exp }, CRM_SIGNING_SECRET);
  }

  /**
   * Verifies a token given a JWT and a secret. Throws an error
   * if there is a problem verifying.
   *
   * @param      {string}  token   The token
   * @param      {string}  secret  The secret
   * @return     {string|object}  { Returns an object or string depending on the JWT }
   */
  private verifyToken(token, secret): string | {} {
    try {
      return jwt.verify(token, secret);
    } catch (e) {
      throw new HttpException(e, HttpStatus.UNAUTHORIZED);
    }
  }
}
